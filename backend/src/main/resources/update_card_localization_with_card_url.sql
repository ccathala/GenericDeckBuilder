-- Vérification par élément
SELECT 
  CASE 
    WHEN card_url LIKE '%/air/%' THEN 'AIR'
    WHEN card_url LIKE '%/arcane/%' THEN 'ARCANE'
    WHEN card_url LIKE '%/feu/%' OR card_url LIKE '%/fire/%' THEN 'FEU'
    WHEN card_url LIKE '%/eau/%' OR card_url LIKE '%/water/%' THEN 'EAU'
    WHEN card_url LIKE '%/vegetal/%' OR card_url LIKE '%/plant/%' THEN 'VÉGÉTAL'
    WHEN card_url LIKE '%/mineral/%' THEN 'MINÉRAL'
    ELSE 'AUTRE'
  END as element,
  COUNT(*) as nombre
FROM card_localization
WHERE card_url IS NOT NULL AND card_url != ''
GROUP BY 
  CASE 
    WHEN card_url LIKE '%/air/%' THEN 'AIR'
    WHEN card_url LIKE '%/arcane/%' THEN 'ARCANE'
    WHEN card_url LIKE '%/feu/%' OR card_url LIKE '%/fire/%' THEN 'FEU'
    WHEN card_url LIKE '%/eau/%' OR card_url LIKE '%/water/%' THEN 'EAU'
    WHEN card_url LIKE '%/vegetal/%' OR card_url LIKE '%/plant/%' THEN 'VÉGÉTAL'
    WHEN card_url LIKE '%/mineral/%' THEN 'MINÉRAL'
    ELSE 'AUTRE'
  END
ORDER BY element;

